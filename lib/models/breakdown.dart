/// Розкладка місяця за категоріями: скільки з'їла кожна.
///
/// Запит до бази віддає суми в довільному порядку
/// (`TransactionRepository.watchCategoryBreakdown`), упорядкування —
/// тут, у чистій функції, щоб його перевіряв тест.
library;

typedef CategoryTotal = ({String categoryId, int totalMinor});

/// Сортує за спаданням суми.
///
/// **Відсотків тут немає свідомо.** Спершу вони були — частка під
/// назвою кожної категорії, — і після дня вжитку виявились зайвими:
/// список відсортований, тож ранг несе порядок, а «куди найбільше»
/// відповідає перший рядок. Ціна відсотка була не нульова: він робив
/// рядок дворівневим (68dp замість 56), тобто на три категорії менше
/// в полі зору, і тягнув окреме правило для `<1%`, бо округлення до
/// цілого показувало реальні витрачені гроші як «0%».
///
/// **Порядок детермінований.** При рівних сумах вирішує `categoryId` —
/// інакше дві категорії з однаковою сумою мінялися б місцями між
/// перемальовками залежно від того, у якому порядку їх віддала база.
List<CategoryTotal> rankedTotals(List<CategoryTotal> totals) {
  final ranked = [...totals];
  ranked.sort((a, b) {
    final byAmount = b.totalMinor.compareTo(a.totalMinor);
    return byAmount != 0 ? byAmount : a.categoryId.compareTo(b.categoryId);
  });
  return ranked;
}
