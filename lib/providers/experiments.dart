import 'package:flutter_riverpod/flutter_riverpod.dart';

/// Прапорці візуальних експериментів (2026-08-16).
///
/// Обидва ефекти під ними неможливо оцінити зі скріншота: зерно б'ється
/// або не б'ється з дизерингом конкретної OLED-матриці, а ореол під
/// метриками або читається як стан місяця, або як брудна пляма. Тому
/// вони вмикаються перемикачем на пристрої, а не рішенням у коді.
///
/// Стан живе в пам'яті й не пишеться в базу навмисно: це експеримент,
/// а не функція, і колонка в налаштуваннях означала б міграцію, яку
/// потім довелось би прибирати. Ціна — прапорці скидаються при
/// холодному старті.
///
/// Перед релізом: [kShowExperiments] у `false`, і трі-шейкер прибирає
/// й перемикачі, і самі ефекти.
const kShowExperiments = true;

